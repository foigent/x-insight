func TestServiceIdentityCLIIsRootGatedAndUsesBoundedStoreContract(t *testing.T) {
	if err := runServiceIdentity(
		context.Background(),
		hostctl.Paths{},
		[]string{"list"},
		&bytes.Buffer{},
		false,
	); err == nil || !strings.Contains(err.Error(), "require root") {
		t.Fatalf("non-root service identity command err=%v", err)
	}

	now := time.Date(2026, 7, 31, 3, 0, 0, 0, time.UTC)
	expiresAt := now.Add(24 * time.Hour)
	store := &serviceIdentityStoreStub{
		credential: workspace.ServiceCredential{
			ServiceIdentity: workspace.ServiceIdentity{
				ID: "xsi_0123456789abcdefghijkl", DisplayName: "review-agent",
				Status: "active", Permissions: []string{"evidence.read", "evidence.cite"},
				CreatedBySubject: "root", CreatedAt: now, UpdatedAt: now, ExpiresAt: &expiresAt,
			},
			Token:       "xib_0123456789abcdefghijklmnopqrstuvwxyzABCDE",
			TokenPrefix: "xib_01234567",
			ExpiresAt:   expiresAt,
		},
	}
	var output bytes.Buffer
	if err := runServiceIdentityCommand(
		context.Background(),
		store,
		[]string{"create", "--name", "review-agent", "--expires-at", expiresAt.Format(time.RFC3339)},
		&output,
		now,
	); err != nil {
		t.Fatalf("create service identity: %v", err)
	}
	if store.created.Actor.Kind != "root" || store.created.Actor.Ref != "root" ||
		store.created.Input.DisplayName != "review-agent" ||
		!store.created.Input.ExpiresAt.Equal(expiresAt) ||
		!store.created.Now.Equal(now) ||
		!strings.Contains(output.String(), `"token": "xib_`) {
		t.Fatalf("create call=%+v output=%s", store.created, output.String())
	}

	output.Reset()
	store.identities = []workspace.ServiceIdentity{store.credential.ServiceIdentity}
	if err := runServiceIdentityCommand(
		context.Background(), store, []string{"list"}, &output, now,
	); err != nil {
		t.Fatalf("list service identities: %v", err)
	}
	if strings.Contains(output.String(), store.credential.Token) ||
		!strings.Contains(output.String(), `"display_name": "review-agent"`) {
		t.Fatalf("unsafe list output=%s", output.String())
	}

	output.Reset()
	if err := runServiceIdentityCommand(
		context.Background(),
		store,
		[]string{"revoke", "--id", store.credential.ServiceIdentity.ID, "--reason", "rotation"},
		&output,
		now,
	); err != nil {
		t.Fatalf("revoke service identity: %v", err)
	}
	if store.revoked.ID != store.credential.ServiceIdentity.ID ||
		store.revoked.Actor.Kind != "root" ||
		store.revoked.Reason != "rotation" ||
		!store.revoked.Now.Equal(now) {
		t.Fatalf("revoke call=%+v", store.revoked)
	}
}

