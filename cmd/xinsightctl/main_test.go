func TestFeedCredentialCLIEmitsOnlyStrictPublicBundleAndStatus(t *testing.T) {
	root := t.TempDir()
	t.Setenv(hostctl.AllowTestRootEnv, "1")
	t.Setenv(hostctl.TestRootEnv, root)

	var prepareOutput bytes.Buffer
	if err := run(
		context.Background(),
		[]string{"feed-credential", "prepare"},
		&prepareOutput,
	); err != nil {
		t.Fatalf("prepare: %v", err)
	}
	var registration hostctl.FeedCredentialRegistration
	decoder := json.NewDecoder(bytes.NewReader(prepareOutput.Bytes()))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&registration); err != nil {
		t.Fatalf("decode strict public bundle: %v", err)
	}
	if registration.SchemaVersion != hostctl.FeedCredentialRegistrationSchema ||
		registration.TokenFormat != hostctl.FeedCredentialTokenFormat ||
		registration.VerifierScheme != hostctl.FeedCredentialVerifierScheme {
		t.Fatalf("registration=%+v", registration)
	}

	tokenPath := filepath.Join(root, "etc", "x-insight", "unirouter-feed.key.next")
	token, err := os.ReadFile(tokenPath)
	if err != nil {
		t.Fatalf("read isolated staged credential: %v", err)
	}
	if bytes.Contains(prepareOutput.Bytes(), token) {
		t.Fatal("prepare CLI output leaked the raw token")
	}

	var statusOutput bytes.Buffer
	if err := run(
		context.Background(),
		[]string{"feed-credential", "status"},
		&statusOutput,
	); err != nil {
		t.Fatalf("status: %v", err)
	}
	if bytes.Contains(statusOutput.Bytes(), token) ||
		!strings.Contains(statusOutput.String(), `"status": "prepared"`) ||
		!strings.Contains(statusOutput.String(), `"binding_matches": true`) {
		t.Fatalf("unsafe or incomplete status output=%s", statusOutput.String())
	}

	var abortOutput bytes.Buffer
	if err := run(
		context.Background(),
		[]string{
			"feed-credential",
			"abort",
			"--operation-id", registration.OperationID,
			"--verifier-sha256", registration.VerifierSHA256,
		},
		&abortOutput,
	); err != nil {
		t.Fatalf("abort: %v", err)
	}
	if bytes.Contains(abortOutput.Bytes(), token) ||
		!strings.Contains(abortOutput.String(), `"status": "absent"`) {
		t.Fatalf("unsafe or incomplete abort output=%s", abortOutput.String())
	}
}

